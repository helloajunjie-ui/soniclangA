// Package consolidate runs the L1 → L2 → L3 pipeline as a background job
// (DESIGN §5 job / §6.5 ①). It groups atomic memories into readable scene
// documents and refreshes the L3 persona.
//
// The safety boundary is the whole point of this package:
//
//	contradictions are ONLY registered in memory/conflicts.json.
//
// Auto-merging two conflicting memories is a poisoning vector — a single bad
// extraction could silently overwrite a correct one and nothing would ever
// surface it. So consolidation reports {claimA, claimB, sourceIds} and waits
// for a human to adjudicate via the conflicts API. Nothing here deletes or
// edits an existing L1 memory.
package consolidate

import (
	"context"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
	"sync"
	"time"

	"github.com/agenthub/agent-proxy/internal/job"
	"github.com/agenthub/agent-proxy/internal/llm"
	"github.com/agenthub/agent-proxy/internal/llmjson"
	"github.com/agenthub/agent-proxy/internal/memory"
	"github.com/agenthub/agent-proxy/internal/provider"
)

// TypeConsolidate is the job type name.
const TypeConsolidate = "memory_consolidate"

// Payload is the job body. JobID is generated by the submitter so the worker
// can publish progress against it (job.Worker.Run does not receive the id).
type Payload struct {
	JobID      string `json:"jobId,omitempty"`
	ProviderID string `json:"providerId"`
	Model      string `json:"model"`
	UpdateL3   bool   `json:"updateL3"`
	MinItems   int    `json:"minItems,omitempty"`
}

// Report summarises one consolidation run.
type Report struct {
	Scenes    int   `json:"scenes"`
	Conflicts int   `json:"conflicts"`
	Persona   bool  `json:"persona"`
	StartedAt int64 `json:"startedAt"`
}

// Worker runs consolidation jobs.
type Worker struct {
	mem  *memory.Service
	prov *provider.Service
	jobs *job.Service
	mu   sync.RWMutex
	last map[string]Report
}

// New constructs the consolidation Worker.
func New(mem *memory.Service, prov *provider.Service, j *job.Service) *Worker {
	return &Worker{mem: mem, prov: prov, jobs: j, last: map[string]Report{}}
}

// Type implements job.Worker.
func (w *Worker) Type() string { return TypeConsolidate }

// LastReport returns the report of the most recent run for a job id.
func (w *Worker) LastReport(jobID string) (Report, bool) {
	w.mu.RLock()
	defer w.mu.RUnlock()
	r, ok := w.last[jobID]
	return r, ok
}

// Run implements job.Worker.
func (w *Worker) Run(ctx context.Context, payload []byte) error {
	var p Payload
	if err := json.Unmarshal(payload, &p); err != nil {
		return err
	}
	progress := func(pct int, msg string) {
		if p.JobID != "" && w.jobs != nil {
			w.jobs.ReportProgress(p.JobID, pct, msg)
		}
	}
	progress(5, "加载 L1 记忆")
	items := w.mem.List(memory.ListFilter{Level: memory.LevelL1, Include: true})
	minItems := p.MinItems
	if minItems <= 0 {
		minItems = 3
	}
	rep := Report{StartedAt: time.Now().UnixMilli()}
	if len(items) < minItems {
		progress(100, fmt.Sprintf("L1 记忆不足（%d < %d），跳过归纳", len(items), minItems))
		w.record(p.JobID, rep)
		return nil
	}
	if p.ProviderID == "" || p.Model == "" || w.prov == nil {
		return fmt.Errorf("consolidation requires a provider/model")
	}
	sort.Slice(items, func(i, j int) bool {
		if items[i].Scene != items[j].Scene {
			return items[i].Scene < items[j].Scene
		}
		return items[i].Category < items[j].Category
	})

	// Snapshot the existing scenes first. Consolidation is periodic, and a model
	// rarely picks byte-identical scene names twice: without this the scene list
	// would accumulate near-duplicates ("项目概况" / "项目概览") on every run.
	existing := map[string][]string{} // scene -> memberIds
	bodies := map[string]string{}     // scene -> markdown body
	for _, name := range w.mem.Scenes() {
		body, members, err := w.mem.Scene(name)
		if err != nil {
			continue
		}
		existing[name] = members
		bodies[name] = body
	}

	progress(20, "归纳 L2 场景")
	plan, err := w.planScenes(ctx, p, items, sortedKeys(existing))
	if err != nil {
		return err
	}

	progress(60, "写入场景文档")
	valid := map[string]bool{}
	for _, id := range plan.allMemberIDs {
		valid[id] = true
	}
	// A memory belongs to exactly one scene; remember this run's assignment so
	// stale entries from earlier runs can be cleaned up.
	assigned := map[string]string{}
	for _, sc := range plan.Scenes {
		for _, id := range sc.MemberIds {
			if valid[id] {
				assigned[id] = sc.Name
			}
		}
	}
	for name, members := range existing {
		kept := make([]string, 0, len(members))
		for _, id := range members {
			if other, ok := assigned[id]; ok && other != name {
				continue // moved to a different scene by this run
			}
			kept = append(kept, id)
		}
		if len(kept) == 0 {
			// every member was regrouped elsewhere; the scene is now stale
			_ = w.mem.DeleteScene(name)
			delete(existing, name)
			continue
		}
		if len(kept) != len(members) {
			existing[name] = kept
			_ = w.mem.SaveScene(name, bodies[name], kept)
		}
	}
	for _, sc := range plan.Scenes {
		name := strings.TrimSpace(sc.Name)
		if name == "" {
			continue
		}
		members := make([]string, 0, len(sc.MemberIds))
		for _, id := range sc.MemberIds {
			if valid[id] {
				members = append(members, id)
			}
		}
		if err := w.mem.SaveScene(name, renderScene(name, sc.Summary, items, members), members); err != nil {
			return err
		}
		rep.Scenes++
	}

	// contradictions: register only. Never rewrite a memory here.
	progress(75, "登记矛盾")
	for _, c := range plan.Conflicts {
		if strings.TrimSpace(c.ClaimA) == "" || strings.TrimSpace(c.ClaimB) == "" {
			continue
		}
		ids := make([]string, 0, len(c.SourceIds))
		for _, id := range c.SourceIds {
			if valid[id] {
				ids = append(ids, id)
			}
		}
		_, err := w.mem.AddConflict(memory.Conflict{
			ClaimA:    c.ClaimA,
			ClaimB:    c.ClaimB,
			SourceIds: ids,
			Conflict:  c.Conflict,
		})
		if err == nil {
			rep.Conflicts++
		}
	}

	if p.UpdateL3 {
		progress(90, "更新 L3 画像")
		md, err := w.planPersona(ctx, p, items, plan.Scenes)
		if err != nil {
			return err
		}
		if strings.TrimSpace(md) != "" {
			if err := w.mem.SetPersona(md); err != nil {
				return err
			}
			rep.Persona = true
		}
	}
	progress(100, "完成")
	w.record(p.JobID, rep)
	return nil
}

func sortedKeys(m map[string][]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func (w *Worker) record(jobID string, r Report) {
	if jobID == "" {
		return
	}
	w.mu.Lock()
	w.last[jobID] = r
	w.mu.Unlock()
}

// ---- L2 planning ----

type planResult struct {
	Scenes       []scene    `json:"scenes"`
	Conflicts    []conflict `json:"conflicts"`
	allMemberIDs []string
}

type scene struct {
	Name      string   `json:"name"`
	Summary   string   `json:"summary"`
	MemberIds []string `json:"memberIds"`
}

type conflict struct {
	ClaimA    string   `json:"claimA"`
	ClaimB    string   `json:"claimB"`
	SourceIds []string `json:"sourceIds"`
	Conflict  string   `json:"conflict"`
}

const scenePrompt = `你是记忆巩固器。把下列原子记忆（L1）归纳成场景知识块（L2）。

规则：
1. 按主题/项目/场景分组，每个场景给出简短名称（2-8 字）与一段归纳说明。
2. memberIds 必须只使用下面给出的 id，且每个 id 最多归入一个场景。
3. 若两条记忆互相矛盾：不要合并、不要判断谁对，把它登记到 conflicts
   （claimA/claimB 写两条主张原文，sourceIds 写两条记忆的 id，conflict 写冲突点）。
   sourceIds 的顺序有约定：第一个是 claimA 对应的记忆 id，第二个是 claimB 对应的。
   裁定时要按这个顺序找到该失效的那一条，顺序错了就会停用错记忆。
4. 不确定就少分组；宁可多几个小场景，也不要硬凑。
5. 下方会给出已存在的场景名。若记忆属于其中某个场景，必须沿用完全相同的名称，
   不得新建近义名称（避免"项目概况"/"项目概览"这类重复）。

只输出 JSON：
{"scenes":[{"name":"...","summary":"...","memberIds":["..."]}],"conflicts":[{"claimA":"...","claimB":"...","sourceIds":["..."],"conflict":"..."}]}`

func (w *Worker) planScenes(ctx context.Context, p Payload, items []*memory.Memory, existing []string) (*planResult, error) {
	rt, err := w.prov.GetRuntime(p.ProviderID)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	if len(existing) > 0 {
		b.WriteString("已存在的场景（请优先沿用这些名称）：\n")
		for _, n := range existing {
			fmt.Fprintf(&b, "- %s\n", n)
		}
		b.WriteString("\n")
	}
	b.WriteString("原子记忆列表：\n\n")
	for _, m := range items {
		cat := m.Category
		if cat == "" {
			cat = "fact"
		}
		fmt.Fprintf(&b, "- id=%s [%s/%s] %s\n", m.ID, cat, m.Scene, m.Content)
	}
	ctx2, cancel := context.WithTimeout(ctx, 180*time.Second)
	defer cancel()
	raw, err := llm.ChatObject(ctx2, rt, p.Model, []provider.Message{
		{Role: "system", Content: scenePrompt},
		{Role: "user", Content: b.String()},
	}, provider.CallOptions{Temperature: 0.2, MaxTokens: 2000})
	if err != nil {
		return nil, err
	}
	var out planResult
	if err := llmjson.UnmarshalInto(raw, &out); err != nil {
		return nil, fmt.Errorf("parse consolidation: %w", err)
	}
	seen := map[string]bool{}
	for _, sc := range out.Scenes {
		for _, id := range sc.MemberIds {
			if !seen[id] {
				seen[id] = true
				out.allMemberIDs = append(out.allMemberIDs, id)
			}
		}
	}
	for _, c := range out.Conflicts {
		for _, id := range c.SourceIds {
			if !seen[id] {
				seen[id] = true
				out.allMemberIDs = append(out.allMemberIDs, id)
			}
		}
	}
	return &out, nil
}

// renderScene writes the scene document. Membership comes from the member id
// list decided by the pipeline, never by matching the memory's own scene hint:
// memories created by hand (or before scenes existed) carry an empty hint and
// would otherwise be listed under every scene at once.
func renderScene(name, summary string, items []*memory.Memory, memberIDs []string) string {
	want := map[string]bool{}
	for _, id := range memberIDs {
		want[id] = true
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", name)
	if strings.TrimSpace(summary) != "" {
		b.WriteString(strings.TrimSpace(summary) + "\n\n")
	}
	b.WriteString("## 组成记忆 (L1)\n\n")
	for _, m := range items {
		if !want[m.ID] {
			continue
		}
		b.WriteString(fmt.Sprintf("- `%s` %s\n", m.ID, m.Content))
	}
	b.WriteString("\n<!-- 本文件由 consolidation 生成；正文可手工编辑，组成记忆以 memory/index.json 为准 -->\n")
	return b.String()
}

// ---- L3 persona ----

const personaPrompt = `你是画像维护器。基于现有画像与场景归纳，更新用户画像（L3）。

规则：
1. 只保留稳定、长期成立的结论；不确定的内容放到「待观察」。
2. 保留现有画像中仍然成立的人工修改，不要推翻人手写的内容。
3. 用 Markdown，包含小节标题；控制在 40 行以内。
4. 不要编造列表中不存在的信息。

只输出 JSON：{"persona":"<markdown 正文>"}`

func (w *Worker) planPersona(ctx context.Context, p Payload, items []*memory.Memory, scenes []scene) (string, error) {
	rt, err := w.prov.GetRuntime(p.ProviderID)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	cur := strings.TrimSpace(w.mem.Persona())
	if cur != "" {
		b.WriteString("## 现有画像\n\n" + cur + "\n\n")
	} else {
		b.WriteString("## 现有画像\n\n（空）\n\n")
	}
	if len(scenes) > 0 {
		b.WriteString("## 场景归纳\n\n")
		for _, sc := range scenes {
			fmt.Fprintf(&b, "- %s：%s\n", sc.Name, sc.Summary)
		}
		b.WriteString("\n")
	}
	b.WriteString("## 高权重原子记忆\n\n")
	sort.Slice(items, func(i, j int) bool { return items[i].Importance > items[j].Importance })
	n := len(items)
	if n > 30 {
		n = 30
	}
	for _, m := range items[:n] {
		fmt.Fprintf(&b, "- %s\n", m.Content)
	}
	ctx2, cancel := context.WithTimeout(ctx, 180*time.Second)
	defer cancel()
	msgs := []provider.Message{
		{Role: "system", Content: personaPrompt},
		{Role: "user", Content: b.String()},
	}
	opts := provider.CallOptions{Temperature: 0.3, MaxTokens: 2000}
	raw, err := llm.ChatObject(ctx2, rt, p.Model, msgs, opts)
	if err != nil {
		// The profile is a document, not a record: a model that ignores the JSON
		// wrapper often still writes a perfectly usable one, so fall back to the
		// plain reply instead of discarding it.
		plain, perr := llm.Chat(ctx2, rt, p.Model, msgs, opts)
		if perr != nil || strings.TrimSpace(plain) == "" {
			return "", err
		}
		return strings.TrimSpace(plain), nil
	}
	var out struct {
		Persona string `json:"persona"`
	}
	if err := llmjson.UnmarshalInto(raw, &out); err != nil || strings.TrimSpace(out.Persona) == "" {
		return "", fmt.Errorf("persona reply carried no persona field")
	}
	return strings.TrimSpace(out.Persona), nil
}
