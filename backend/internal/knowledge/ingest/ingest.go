// Package ingest implements the asynchronous document-ingestion worker
// (DESIGN §5 job / §6.4). Uploads return a jobId immediately; parsing, chunking
// and embedding then run in the job worker pool with progress published to
// subscribers, so HTTP/SSE connections are never blocked.
package ingest

import (
	"context"
	"encoding/json"
	"os"
	"path/filepath"
	"sync"
	"time"

	"github.com/agenthub/agent-proxy/internal/job"
	"github.com/agenthub/agent-proxy/internal/knowledge"
)

// Job type name for ingestion.
const TypeIngestDocument = "ingest_document"

// Payload is the job body for one ingestion task. JobID is generated by the
// submitter before enqueueing so the worker can publish progress against it
// (job.Worker.Run does not receive the job id).
type Payload struct {
	JobID        string `json:"jobId,omitempty"`
	CollectionID string `json:"collectionId"`
	DocID        string `json:"docId"`
	// Raw is the document bytes for small uploads; RawPath points at a staged
	// file for larger ones (multipart is staged to disk to avoid buffering).
	Raw     []byte `json:"raw,omitempty"`
	RawPath string `json:"rawPath,omitempty"`
}

// Worker runs ingestion jobs.
type Worker struct {
	knowledge *knowledge.Service
	jobs      *job.Service
	stageDir  string
	mu        sync.RWMutex
	// last reports the most recent stage message per job (for status views).
	last map[string]string
}

// New constructs the ingestion Worker.
func New(k *knowledge.Service, j *job.Service, stageDir string) *Worker {
	if stageDir != "" {
		_ = os.MkdirAll(stageDir, 0o755)
	}
	return &Worker{knowledge: k, jobs: j, stageDir: stageDir, last: map[string]string{}}
}

// Type implements job.Worker.
func (w *Worker) Type() string { return TypeIngestDocument }

// Stage writes upload bytes to a staging file, returning a payload path.
func (w *Worker) Stage(docID string, data []byte) (string, error) {
	if w.stageDir == "" {
		return "", nil
	}
	p := filepath.Join(w.stageDir, docID)
	if err := os.WriteFile(p, data, 0o644); err != nil {
		return "", err
	}
	return p, nil
}

// Run implements job.Worker: parses, chunks, embeds and indexes the document.
func (w *Worker) Run(ctx context.Context, payload []byte) error {
	var p Payload
	if err := json.Unmarshal(payload, &p); err != nil {
		return err
	}
	// job id is not part of the worker contract; progress is reported via a
	// closure keyed by document id so the caller can follow along.
	doc, err := w.knowledge.GetDoc(p.CollectionID, p.DocID)
	if err != nil {
		return err
	}
	data := p.Raw
	if p.RawPath != "" {
		if b, e := os.ReadFile(p.RawPath); e == nil {
			data = b
		} else {
			return e
		}
	}
	cbJobID := p.JobID
	progress := func(pct int, msg string) {
		w.setLast(p.DocID, msg)
		if cbJobID != "" && w.jobs != nil {
			w.jobs.ReportProgress(cbJobID, pct, msg)
		}
	}
	progress(1, "入队完成")
	err = w.knowledge.Ingest(ctx, p.CollectionID, doc, data, progress)
	w.setLast(p.DocID, time.Now().Format("15:04:05")+" 摄取"+
		statusWord(err))
	// stage file is no longer needed once indexed
	if p.RawPath != "" {
		_ = os.Remove(p.RawPath)
	}
	return err
}

func statusWord(err error) string {
	if err != nil {
		return "失败：" + err.Error()
	}
	return "完成"
}

func (w *Worker) setLast(docID, msg string) {
	w.mu.Lock()
	w.last[docID] = msg
	w.mu.Unlock()
}

// StageOf returns the last known stage message for a document.
func (w *Worker) StageOf(docID string) string {
	w.mu.RLock()
	defer w.mu.RUnlock()
	return w.last[docID]
}
